-- BertBooker — the D1 schema.
-- Applied via: wrangler d1 migrations apply bertbooker_db [--local|--remote]
--
-- This is the whole schema in one file. Program reference rows are seeded
-- separately by seed/programs.sql, and airport rows by seed/airports.sql; both
-- live outside migrations/ so they stay re-runnable.
--
-- Statement order follows the foreign keys, which D1 enforces: `programs` and
-- `users` before anything referencing them, `search_runs` before the three
-- tables that cascade off it, `tracked_routes` before `alert_outbox`.


-- ===========================================================================
-- Reference data
-- ===========================================================================

-- Loyalty programs and how the couple's currencies feed them.
-- Mirrors shared/src/data/programs.ts — keep the two in sync.
CREATE TABLE IF NOT EXISTS programs (
  code              TEXT PRIMARY KEY,
  name              TEXT NOT NULL,
  kind              TEXT NOT NULL CHECK (kind IN ('airline', 'hotel')),
  alliance          TEXT,                       -- 'star'|'oneworld'|'skyteam'|NULL
  transfer_partners TEXT NOT NULL DEFAULT '[]', -- JSON: [{currency, ratio}]
  is_active         INTEGER NOT NULL DEFAULT 1
);

-- Airport reference data (searchable). Rows come from seed/airports.sql,
-- generated by scripts/build-airports.mjs from the public-domain OurAirports
-- dataset. Standalone: no FK points at it and it points at nothing.
CREATE TABLE IF NOT EXISTS airports (
  ident     TEXT PRIMARY KEY,   -- OurAirports unique identifier (e.g. KJFK)
  type      TEXT,               -- large_airport | medium_airport | heliport | ...
  name      TEXT NOT NULL,
  iata      TEXT,               -- IATA code (may be empty for non-commercial fields)
  icao      TEXT,               -- ICAO / GPS code
  city      TEXT,               -- municipality
  country   TEXT,               -- ISO 3166-1 alpha-2
  region    TEXT,               -- ISO 3166-2 region
  continent TEXT,
  latitude  REAL,
  longitude REAL,
  scheduled INTEGER NOT NULL DEFAULT 0  -- 1 if the airport has scheduled service
);
CREATE INDEX IF NOT EXISTS idx_airports_iata ON airports(iata);
CREATE INDEX IF NOT EXISTS idx_airports_name ON airports(name);
CREATE INDEX IF NOT EXISTS idx_airports_city ON airports(city);

-- The two people using the app. There is no Cloudflare Access in front of this
-- worker, so identity is the single shared `APP_USER_EMAIL` behind the password
-- gate — `Cf-Access-Authenticated-User-Email` is deliberately ignored
-- (api/src/identity.ts).
CREATE TABLE IF NOT EXISTS users (
  email        TEXT PRIMARY KEY,
  display_name TEXT,
  created_at   INTEGER NOT NULL DEFAULT (unixepoch() * 1000)
);


-- ===========================================================================
-- What the user asked for
-- ===========================================================================

-- A monitored route: a SET of city pairs, a date window, and the filters that
-- narrow its finds.
--
-- `origins`/`destinations` are nullable JSON arrays beside the scalar
-- `origin`/`destination`, which stay as the route's PRIMARY airport. Readers use
-- COALESCE(origins, json_array(origin)), so a row carrying only the scalar still
-- works. `cabins` and `currencies` have the same shape and the same rule: NULL
-- means "no filter", not "none".
--
-- Searching SEA/PDX -> NRT/HND is the cross product of two airport lists. A
-- route expands into a pair list, and everything downstream — the search plan,
-- the coverage claim, the prune — already works per pair because co-terminal
-- answers forced it to (see `routesTouched` in
-- shared/src/ingest/apply.ts). shared/src/routing.ts turns this
-- into pair groups; ONE group is ONE seats.aero call however many pairs it
-- holds, because the API takes comma-delimited airports.
CREATE TABLE IF NOT EXISTS tracked_routes (
  id              INTEGER PRIMARY KEY AUTOINCREMENT,
  user_email      TEXT NOT NULL REFERENCES users(email),
  origin          TEXT NOT NULL,   -- IATA; the route's primary origin
  destination     TEXT NOT NULL,   -- IATA; the route's primary destination
  origins         TEXT,            -- JSON array of IATA; NULL = use the scalar
  destinations    TEXT,            -- JSON array of IATA; NULL = use the scalar
  date_start      TEXT NOT NULL,   -- ISO date
  date_end        TEXT NOT NULL,   -- ISO date (inclusive)
  -- A representative cabin, still written on insert. `cabins` is what actually
  -- filters the route's finds.
  cabin           TEXT NOT NULL DEFAULT 'business',
  cabins          TEXT,            -- JSON array of cabin codes; NULL = any
  currencies      TEXT,            -- JSON array of currency codes; NULL = any
  min_seats       INTEGER NOT NULL DEFAULT 2,
  programs        TEXT,            -- JSON array of program codes; NULL = all
  kind            TEXT NOT NULL DEFAULT 'flight' CHECK (kind IN ('flight', 'hotel')),
  hotel_id        TEXT,
  last_checked_at INTEGER,
  created_at      INTEGER NOT NULL DEFAULT (unixepoch() * 1000),

  -- A READ filter, and only a read filter. Gather wide, query narrow:
  -- connecting itineraries are still gathered, still stored and still claim
  -- coverage; this decides only what the route's own pane shows. It is applied
  -- in the Routes page join beside `cabins` / `currencies` / `min_seats`, which is
  -- the one place a route's filters are ever applied — nothing about the search
  -- plan or the coverage claim reads it, and nothing may.
  direct_only     INTEGER NOT NULL DEFAULT 0,

  -- The one per-route setting that changes what is GATHERED, not merely what is
  -- shown, and the difference is the whole point: a round trip needs award space
  -- in BOTH directions, and no filter can surface data that was never fetched.
  --
  -- It is nearly free, which is what makes it a checkbox rather than a second
  -- route. seats.aero takes comma-delimited airports, so a round-trip search
  -- puts every airport on BOTH sides of one call —
  -- `origin_airport=HND,SEA&destination_airport=HND,SEA` returns SEA->HND and
  -- HND->SEA together, with the self-pairs dropped by `routePairs`. Same chunks,
  -- same call count, same quota as the one-way search it replaces. See
  -- `roundTripSpec` in shared/src/routing.ts.
  --
  -- Two consequences worth knowing:
  --   * The ROUTES PAGE JOIN must match both directions for these routes, or the
  --     return legs this gathers would be stored and invisible.
  --   * Roughly twice the rows come back per chunk, so a busy route is likelier
  --     to paginate out at SEATSAERO_MAX_PAGES. That NARROWS the coverage claim
  --     honestly (`runSeatsAeroChunk` claims only through the furthest date it
  --     actually saw); it does not corrupt anything.
  round_trip      INTEGER NOT NULL DEFAULT 0,

  -- -------------------------------------------------------------------------
  -- Alerts (api/src/alerts/, docs/ALERTS.md)
  -- -------------------------------------------------------------------------

  -- Off by default, so a newly created route schedules nothing.
  alerts_enabled  INTEGER NOT NULL DEFAULT 0,

  -- Where the digest goes. NULL = the route's own `user_email`, which is the
  -- shared identity — so the common case needs no decision. Writes are checked
  -- against ALERT_ALLOWED_RECIPIENTS: with one shared password as the only auth,
  -- an unchecked value here would make the Worker an arbitrary-recipient sender
  -- on a verified domain, and the domain's sending reputation is not something a
  -- typo should be able to spend.
  alert_email     TEXT,

  -- JSON array of ChangeType (shared/src/diff.ts): new | more_seats |
  -- price_drop | gone. NULL = the default set, ["new","price_drop"].
  --
  -- READ THIS BEFORE COPYING THE NEIGHBOURING COLUMNS' CONVENTION. `cabins` and
  -- `currencies` treat NULL *and* `[]` alike as "no filter, everything matches".
  -- Here `[]` would mean the opposite — nothing ever fires — so it is REJECTED
  -- at the API with a 400 rather than stored. NULL is the only way to say
  -- "default". A route with alerts on and no type selected is a route that
  -- silently never alerts, which is the single most plausible way for this
  -- feature to look broken while behaving exactly as configured.
  --
  -- `gone` is not in the default set on purpose: most disappearances are cache
  -- churn or dates ageing out of the window, and it is the one type that cannot
  -- be intersected against the finds query (there is no current row left to
  -- filter), so it honours fewer of the route's filters than the others do.
  alert_on        TEXT,

  -- Minimum price drop, in percent, before `price_drop` is worth an email.
  -- Defaults to 5 rather than 0: seats.aero re-quotes constantly and a 1%
  -- movement is noise that would train you to ignore the mail.
  alert_min_drop_pct INTEGER NOT NULL DEFAULT 5,

  -- THREE CLOCKS, and each one is load-bearing. Collapsing any two re-creates a
  -- bug the others exist to prevent.
  --
  --   last_checked_at        (above) "this route holds real data as of…"
  --                          Written ONLY when a run claimed coverage. Consulted
  --                          by the scheduler as a floor, so a route searched by
  --                          hand five minutes ago is not immediately re-swept.
  --
  --   alert_last_attempt_at  THE PACING CLOCK. Written on every sweep attempt,
  --                          success or failure. Pacing off `last_checked_at`
  --                          instead would hot-loop a permanently-failing route
  --                          forever: that column is never written when a run
  --                          fails, so the route would be due on every single
  --                          tick and burn the day's allowance on a route that
  --                          cannot succeed.
  --
  --   alert_last_digest_at   THE EMAIL CLOCK, and what makes the first sweep
  --                          silent. `diffAvailability` compares against the last
  --                          snapshot FOR THAT SOURCE, so a route that has not
  --                          been searched recently classifies everything it
  --                          finds as `new` plus a wall of `gone` — thousands of
  --                          changes, truncated to MAX_STORED_CHANGES, emailed as
  --                          a meaningless 200-of-3000 digest. A route with this
  --                          NULL therefore performs a BASELINE sweep: it ingests
  --                          normally, emails nothing, and just stamps this
  --                          column. Same rule when alerts are re-enabled on a
  --                          route that has gone dark.
  alert_last_attempt_at INTEGER,
  alert_last_digest_at  INTEGER,

  -- Consecutive failed sweeps, for exponential backoff. Without it a route with
  -- a window entirely in the past, or a spec seats.aero refuses, takes a slot in
  -- every cycle forever — and it is the likeliest real-world fault, because a
  -- date window silently expires just by time passing. Reset to 0 on any sweep
  -- that claims coverage.
  alert_consecutive_failures INTEGER NOT NULL DEFAULT 0
);
-- The scheduler's one hot query is "which alert-enabled route is most overdue".
-- Partial, because alert-enabled routes are a handful out of the table.
CREATE INDEX IF NOT EXISTS idx_tracked_routes_alerts
  ON tracked_routes (alert_last_attempt_at)
  WHERE alerts_enabled = 1;


